"""Cuts the raw narration into the edited voice track using scripts/edl.json.
Outputs public/voice.wav and src/timeline.generated.ts (segment + word-cue times in seconds on the final video timeline)."""
import json, subprocess, os, numpy as np, soundfile as sf
ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
edl = json.load(open(os.path.join(ROOT, 'scripts/edl.json')))
raw, sr = sf.read(os.path.join(ROOT, edl['source']), dtype='float32')
if raw.ndim > 1: raw = raw.mean(1)
pieces, segs, cursor = [], [], 0.0
fade = int(0.012 * sr)
for s in edl['segments']:
    a = raw[int(s['in'] * sr):int(s['out'] * sr)].copy()
    a[:fade] *= np.linspace(0, 1, fade); a[-fade:] *= np.linspace(1, 0, fade)
    segs.append(dict(id=s['id'], start=round(edl['voiceStart'] + cursor, 3), end=round(edl['voiceStart'] + cursor + len(a) / sr, 3), text=s['text'], src=(s['in'], s['out'])))
    pieces += [a, np.zeros(int(s['gap'] * sr), np.float32)]
    cursor += len(a) / sr + s['gap']
voice = np.concatenate(pieces)
tmp = os.path.join(ROOT, 'public/.voice_cut.wav'); sf.write(tmp, voice, sr)
# gentle broadcast chain: rumble cut, light denoise, presence, compression, loudness
subprocess.run(['ffmpeg', '-v', 'error', '-y', '-i', tmp, '-af',
                'highpass=f=85,afftdn=nf=-30,equalizer=f=3200:t=q:w=1.2:g=2.5,equalizer=f=250:t=q:w=1:g=-2,'
                'acompressor=threshold=-20dB:ratio=3:attack=8:release=120:makeup=2,loudnorm=I=-15:TP=-1.5:LRA=7',
                '-ar', '48000', '-ac', '2', os.path.join(ROOT, 'public/voice.wav')], check=True)
os.remove(tmp)
def to_out(t):
    for s in segs:
        if s['src'][0] - 0.05 <= t <= s['src'][1] + 0.05:
            return round(s['start'] + (t - s['src'][0]), 3)
    raise ValueError(f'cue {t} not inside any kept segment')
cues = {k: to_out(v) for k, v in edl['cues'].items()}
total = edl['voiceStart'] + cursor
with open(os.path.join(ROOT, 'src/timeline.generated.ts'), 'w') as f:
    f.write('// AUTO-GENERATED by scripts/build_voice.py from scripts/edl.json — do not edit by hand.\n')
    f.write(f'export const VOICE_START = {edl["voiceStart"]};\n')
    f.write(f'export const VOICE_END = {round(total, 3)};\n')
    f.write('export const SEGMENTS = ' + json.dumps([{k: v for k, v in s.items() if k != "src"} for s in segs], ensure_ascii=False, indent=1) + ' as const;\n')
    f.write('export const CUES = ' + json.dumps(cues, indent=1) + ' as const;\n')
print('voice length', round(cursor, 2), 'video voice end', round(total, 2))
for s in segs: print(f"{s['start']:7.2f} {s['end']:7.2f} {s['id']}")
