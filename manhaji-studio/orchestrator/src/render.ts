/** Regenerate engine/src/episodes/registry.ts from the episode folders (deterministic → safe under concurrency). */
export const syncRegistry = () => {
  const ids = fs
    .readdirSync(P.engineEpisodes, {withFileTypes: true})
    .filter((d) => d.isDirectory() && fs.existsSync(path.join(P.engineEpisodes, d.name, 'index.ts')) && fs.existsSync(path.join(P.engineEpisodes, d.name, 'timeline.preview.json')))
    .map((d) => d.name)
    .sort();
  const body =
    `// AUTO-GENERATED by the orchestrator (syncRegistry). Do not edit.\nimport type {EpisodeModule} from '../kit/Episode';\n` +
    ids.map((id, i) => `import {episode as E${i}} from './${id}';`).join('\n') +
    `\n\nexport const EPISODES: EpisodeModule[] = [${ids.map((_, i) => `E${i}`).join(', ')}];\n`;
  const file = path.join(P.engineEpisodes, 'registry.ts');
  if (!fs.existsSync(file) || fs.readFileSync(file, 'utf8') !== body) {
    const tmp = `${file}.tmp-${process.pid}`;
    fs.writeFileSync(tmp, body);
    fs.renameSync(tmp, file);
  }
  return ids;
};

type Plan = {hook: {duration_sec: number; trim_start_sec: number; trim_end_sec: number | null; key_word_sec: number | null; hold_frames: number; framing: 'fit' | 'fill'; speech: [number, number][]}; voiceover: {lines: {id: string; file: string; duration_sec: number}[]}};

/** Hook timing from the assembly plan. Preview uses the real hook too as soon as it is uploaded. */
const hookTiming = (plan: Plan | null, exitSec: number, publicDir: string) => {
  const usable = plan && plan.hook.duration_sec > 0 && fs.existsSync(path.join(publicDir, 'hook.mp4'));
  if (!usable) return {clipSec: null, holdFrames: 0, keyWordSec: null, tailHoldSec: 0.4};
  const h = plan!.hook;
  const end = h.trim_end_sec ?? h.duration_sec;
  const clipSec = Math.round((end - h.trim_start_sec) * 1000) / 1000;
  const speech = h.speech.map(([a, b]) => [a - h.trim_start_sec, Math.min(b, end) - h.trim_start_sec] as [number, number]).filter(([a, b]) => b > 0 && a < clipSec);
  const kw = h.key_word_sec === null ? null : h.key_word_sec - h.trim_start_sec;
  // the last word must finish before the 3D exit starts → hold the last frame if the clip ends right on speech
  const lastSpeech = speech.length ? speech[speech.length - 1][1] : clipSec;
  const tailHoldSec = Math.max(0.2, exitSec - (clipSec - lastSpeech) + 0.1);
  return {clipSec, holdFrames: kw === null ? 0 : h.hold_frames, keyWordSec: kw, speech, tailHoldSec};
};

export const hasHook = (id: string) => {
  const e = ep(id);
  const f = path.join(e.final, 'assembly_plan.json');
  if (!fs.existsSync(f) || !fs.existsSync(path.join(e.publicDir, 'hook.mp4'))) return null;
  return readContract<Plan>('assembly_plan', f);
};

export const resolveEpisode = (id: string, mode: 'preview' | 'final'): Timeline => {
  const cfg = loadConfig();
  const e = ep(id);
  const script = readContract<{lines: ScriptLine[]; hook: {key_word?: string}}>('script', path.join(e.script, 'script.json'));
  const storyboard = readContract<{scenes: StoryboardScene[]}>('storyboard', path.join(e.script, 'storyboard.json'));
  const settings = {
    fps: cfg.episode.fps,
    wordsPerSec: cfg.episode.speech_rate_words_per_sec,
    lineGapSec: cfg.episode.line_gap_sec,
    sceneLeadSec: cfg.episode.scene_lead_sec,
    sceneOverlapSec: 0.3,
    hookExitSec: 0.9,
  };
  const planFile = path.join(e.final, 'assembly_plan.json');
  const plan = fs.existsSync(planFile) ? readContract<Plan>('assembly_plan', planFile) : null;
  if (mode === 'final' && !plan) throw new Error('final render needs final/assembly_plan.json (run: studio media <ID>)');
  const hook = hookTiming(plan, settings.hookExitSec, e.publicDir);
  const tl = resolveTimeline({
    episodeId: id,
    mode,
    script,
    storyboard,
    // preview keeps estimated line durations even if some recordings already exist
    durations: mode === 'final' && plan ? Object.fromEntries(plan.voiceover.lines.map((l) => [l.id, l.duration_sec])) : undefined,
    hook,
    settings,
  });
  if (mode === 'preview') {
    fs.mkdirSync(e.engineDir, {recursive: true});
    writeJson(path.join(e.engineDir, 'timeline.preview.json'), tl);
  } else writeJson(path.join(e.final, 'timeline.json'), tl);
  return tl;
};

const renderLockTtl = 45 * 60 * 1000;

/** Render with the shared engine. One heavy render at a time across all workers. */
export const renderEpisode = async (id: string, mode: 'preview' | 'final', owner: string) => {
  const e = ep(id);
  const cfg = loadConfig();
  const tl = resolveEpisode(id, mode);
  preparePublicDir(id);
  syncRegistry();
  const script = readContract<{hook: {text: string; key_word?: string}}>('script', path.join(e.script, 'script.json'));
  const plan = hasHook(id);
  const noMusic = readContract<{music?: boolean}>('storyboard', path.join(e.script, 'storyboard.json')).music === false;
  const props = {
    timeline: tl,
    hookText: script.hook.text,
    keyWord: script.hook.key_word,
    media: {
      hookSrc: plan ? 'hook.mp4' : undefined,
      framing: plan?.hook.framing ?? 'fit',
      trimStartSec: plan?.hook.trim_start_sec ?? 0,
      voice: mode === 'final' && plan ? Object.fromEntries(plan.voiceover.lines.map((l) => [l.id, l.file])) : undefined,
      // preview has no voice → no ducking; final ducks ~8 dB under the presenter
      music: noMusic ? null : mode === 'preview' ? {src: 'music/bed.wav', volume: 0.42, ducked: 0.42} : {src: 'music/bed.wav', volume: 0.34, ducked: 0.14},
    },
  };
  const propsFile = path.join(e.production, `props.${mode}.json`);
  writeJson(propsFile, props);
  const out = mode === 'preview' ? path.join(e.motion, 'preview.mp4') : path.join(e.final, 'final.raw.mp4');

  while (!tryLock('render', owner, renderLockTtl)) await new Promise((r) => setTimeout(r, 5000));
  try {
    const args = [
      'remotion', 'render', 'src/index.ts', id, out,
      `--props=${propsFile}`,
      `--public-dir=${e.publicDir}`,
      '--codec=h264', '--crf=18', '--pixel-format=yuv420p', '--color-space=bt709', '--audio-codec=aac', '--audio-bitrate=256k',
      '--log=error',
      ...(mode === 'preview' ? ['--scale=0.5'] : []),
      ...(process.env.REMOTION_BROWSER ? [`--browser-executable=${process.env.REMOTION_BROWSER}`] : []),
    ];
    const r = spawnSync('npx', args, {cwd: P.engine, encoding: 'utf8', maxBuffer: 64 * 1024 * 1024});
    if (r.status !== 0) throw new Error(`render failed (${mode}): ${(r.stderr || r.stdout).slice(-3000)}`);
  } finally {
    unlock('render', owner);
  }

  if (mode === 'final') {
    // mastering pass: platform loudness, video stream copied untouched
    const master = path.join(e.final, 'final.mp4');
    execFileSync(FFMPEG, ['-hide_banner', '-loglevel', 'error', '-y', '-i', out, '-c:v', 'copy', '-af', `loudnorm=I=${cfg.episode.loudness_lufs}:TP=-1:LRA=9`, '-ar', '48000', '-c:a', 'aac', '-b:a', '256k', '-movflags', '+faststart', master]);
    fs.rmSync(out);
    return {file: master, timeline: tl};
  }
  return {file: out, timeline: tl};
};

export type TechReport = {file: string; ok: boolean; checks: {name: string; ok: boolean; detail: string}[]};

/** Automatic Technical QA — measured, not judged. The Quality Agent interprets it. */
export const technicalQA = (file: string, expectedSec: number, mode: 'preview' | 'final'): TechReport => {
  const cfg = loadConfig();
  const checks: TechReport['checks'] = [];
  const add = (name: string, ok: boolean, detail: string) => checks.push({name, ok, detail});
  if (!fs.existsSync(file)) {
    add('exists', false, 'file missing');
    return {file, ok: false, checks};
  }
  const pr = probe(file);
  const meta = JSON.parse(execFileSync('ffprobe', ['-v', 'error', '-show_entries', 'stream=codec_name,codec_type,pix_fmt,r_frame_rate', '-of', 'json', file]).toString()) as {streams: {codec_name: string; codec_type: string; pix_fmt?: string; r_frame_rate?: string}[]};
  const vs = meta.streams.find((s) => s.codec_type === 'video');
  const as = meta.streams.find((s) => s.codec_type === 'audio');
  const W = mode === 'preview' ? cfg.episode.width / 2 : cfg.episode.width;
  const H = mode === 'preview' ? cfg.episode.height / 2 : cfg.episode.height;
  add('opens', pr.hasVideo, `duration ${pr.durationSec.toFixed(2)}s`);
  add('dimensions', pr.width === W && pr.height === H, `${pr.width}×${pr.height} (expected ${W}×${H})`);
  add('fps', vs?.r_frame_rate === `${cfg.episode.fps}/1`, String(vs?.r_frame_rate));
  add('codec', vs?.codec_name === 'h264' && as?.codec_name === 'aac' && vs?.pix_fmt === 'yuv420p', `${vs?.codec_name}/${vs?.pix_fmt} + ${as?.codec_name}`);
  add('duration', Math.abs(pr.durationSec - expectedSec) <= 0.25, `${pr.durationSec.toFixed(2)}s vs timeline ${expectedSec.toFixed(2)}s`);
  const log = execFileSync('sh', ['-c', `${FFMPEG} -hide_banner -nostats -i "${file}" -vf blackdetect=d=0.3:pix_th=0.06 -af ebur128=peak=true -f null - 2>&1 || true`]).toString();
  const blacks = [...log.matchAll(/black_start:([\d.]+) black_end:([\d.]+)/g)].map((m) => [Number(m[1]), Number(m[2])]);
  add('black_frames', blacks.length === 0, blacks.length ? blacks.map(([a, b]) => `${a.toFixed(2)}–${b.toFixed(2)}s`).join(', ') : 'none');
  const I = Number(log.match(/I:\s+(-?[\d.]+) LUFS/g)?.pop()?.match(/-?[\d.]+/)?.[0] ?? NaN);
  const TP = Number(log.match(/Peak:\s+(-?[\d.]+) dBFS/g)?.pop()?.match(/-?[\d.]+/)?.[0] ?? NaN);
  if (mode === 'final') {
    add('loudness', Math.abs(I - cfg.episode.loudness_lufs) <= 1.5, `${I} LUFS (target ${cfg.episode.loudness_lufs})`);
    add('true_peak', TP <= -0.5, `${TP} dBTP`);
  } else {
    add('audio_present', !Number.isNaN(I) && I > -60, `${I} LUFS`);
  }
  return {file, ok: checks.every((c) => c.ok), checks};
};

/** Stills at the given absolute seconds for agents to LOOK at (half-res JPEG contact sheet + singles). */
export const stillsAt = (videoFile: string, seconds: number[], outDir: string) => {
  fs.mkdirSync(outDir, {recursive: true});
  const files: string[] = [];
  for (const s of seconds) {
    const f = path.join(outDir, `t${s.toFixed(2).replace('.', '_')}.jpg`);
    execFileSync(FFMPEG, ['-hide_banner', '-loglevel', 'error', '-y', '-ss', String(Math.max(0, s)), '-i', videoFile, '-frames:v', '1', '-vf', 'scale=540:-1', '-q:v', '4', f]);
    files.push(f);
  }
  return files;
};
