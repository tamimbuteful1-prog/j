"""Episode 04 uses the narration exactly as recorded (no tempo change, no added pauses).
Writes timeline.js (segment times shifted by LEAD_IN) and vo_timed.wav (the original,
with LEAD_IN of silence in front).

Usage: python3 timeline_vo.py narration.mp3 silences.txt out_dir
"""
import json, os, subprocess, sys
LEAD_IN = 0.25
src, silf, out = sys.argv[1:4]
script = json.load(open(os.path.join(os.path.dirname(os.path.abspath(__file__)), "ep_script.json")))
ev = [(l.split(":")[0], float(l.split(": ")[1])) for l in open(silf)]
dur = float(subprocess.check_output(["ffprobe", "-v", "error", "-show_entries", "format=duration", "-of", "csv=p=0", src]))
segs, cur = [], 0.0
for k, v in ev:
    if k == "silence_start":
        segs.append([cur, v])
    else:
        cur = v
if cur < dur - 0.05:
    segs.append([cur, dur])
assert len(segs) == len(script), (len(segs), len(script))
tl = [{"i": i, "a": round(a + LEAD_IN, 3), "b": round(b + LEAD_IN, 3), "text": script[i][0]} for i, (a, b) in enumerate(segs)]
with open(os.path.join(out, "timeline.js"), "w") as fh:
    fh.write("// generated by timeline_vo.py — narration segment times (original timing + lead-in)\n")
    fh.write("window.SEG=" + json.dumps(tl, ensure_ascii=False) + ";\n")
    fh.write(f"window.VO_END={tl[-1]['b']};\n")
subprocess.run(["ffmpeg", "-y", "-loglevel", "error", "-i", src, "-af", f"adelay={int(LEAD_IN*1000)},apad=pad_dur=0.5",
                "-ac", "1", "-ar", "48000", os.path.join(out, "vo_timed.wav")], check=True)
print(f"segments={len(tl)} voice_end={tl[-1]['b']:.2f}s")
