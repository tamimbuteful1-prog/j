"""Write an ESTIMATED timeline.js from a narration script (no recording yet).

Line duration is predicted from the narrator's measured rate in episodes 5–6
(≈ 0.084 s per letter + 0.11 s), gaps ≈ 0.33 s (+0.25 s after a trailing "…").
When the real ElevenLabs recording arrives, timeline_vo.py replaces this file with
measured times, and every scene/subtitle keyed to the segment index follows it.

Usage: python3 est_timeline.py ep_script.json out_dir
"""
import json, re, sys, os
script = json.load(open(sys.argv[1])); out = sys.argv[2]
t, segs = 0.25, []
for i, (line, extra) in enumerate(script):
    n = len(re.sub(r'[«»…،:!؟.\s]', '', line))
    d = 0.084 * n + 0.11
    segs.append({"i": i, "a": round(t, 3), "b": round(t + d, 3), "text": line})
    t += d + 0.33 + (0.25 if line.rstrip('»').endswith('…') else 0) + extra
with open(os.path.join(out, "timeline.js"), "w") as fh:
    fh.write("// ESTIMATED timeline (no narration yet) — generated by shared/est_timeline.py\n")
    fh.write("window.SEG=" + json.dumps(segs, ensure_ascii=False) + ";\n")
    fh.write(f"window.VO_END={segs[-1]['b']};\nwindow.ESTIMATED=true;\n")
print(f"lines={len(segs)} narration_end={segs[-1]['b']:.1f}s  ->  with question+title ≈ {segs[-1]['b']+9.4:.1f}s")
