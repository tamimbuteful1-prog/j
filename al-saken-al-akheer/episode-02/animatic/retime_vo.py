"""Slow the narration slightly (tempo 0.94, pitch untouched) and lengthen pauses
between phrases, so the episode breathes. Writes vo_paced.wav + timeline.js.

Usage: python3 retime_vo.py narration.mp3 silences.txt out_dir
silences.txt = ffmpeg silencedetect (noise=-38dB:d=0.22) lines.
"""
import json, os, subprocess, sys, wave
import numpy as np

TEMPO = 0.94
SR = 48000
LEAD_IN = 0.6
PAUSE_SCALE = 0.6
src, silf, out = sys.argv[1:4]
script = json.load(open(os.path.join(os.path.dirname(__file__), "ep2_script.json")))

ev = [(l.split(":")[0], float(l.split(": ")[1])) for l in open(silf)]
segs, cur = [], 0.0
for k, v in ev:
    if k == "silence_start":
        segs.append([cur, v])
    else:
        cur = v
dur = float(subprocess.check_output(["ffprobe", "-v", "error", "-show_entries", "format=duration", "-of", "csv=p=0", src]))
if cur < dur - 0.05:
    segs.append([cur, dur])
assert len(segs) == len(script), (len(segs), len(script))

raw = os.path.join(out, "_seg.raw")
pieces, timeline, t = [], [], LEAD_IN
for i, (a, b) in enumerate(segs):
    a2, b2 = max(0, a - 0.04), min(dur, b + 0.10)
    subprocess.run(["ffmpeg", "-y", "-loglevel", "error", "-ss", f"{a2}", "-to", f"{b2}", "-i", src,
                    "-af", f"atempo={TEMPO}", "-ac", "1", "-ar", str(SR), "-f", "f32le", raw], check=True)
    x = np.fromfile(raw, np.float32).astype(float)
    n = len(x)
    f = int(0.012 * SR)
    x[:f] *= np.linspace(0, 1, f)
    x[-f:] *= np.linspace(1, 0, f)
    pieces.append((t, x))
    speak_a = t + (a - a2) / TEMPO
    speak_b = speak_a + (b - a) / TEMPO
    timeline.append({"i": i, "a": round(speak_a, 3), "b": round(speak_b, 3), "text": script[i][0]})
    gap_orig = (segs[i + 1][0] - b) if i + 1 < len(segs) else 0
    t = speak_b + max(0.18, gap_orig / TEMPO) + script[i][1] * PAUSE_SCALE

total = t + 0.2
buf = np.zeros(int(total * SR) + SR)
for st, x in pieces:
    s = int(st * SR)
    buf[s:s + len(x)] += x
buf = buf[: int(total * SR)]
buf /= np.abs(buf).max() + 1e-9
buf *= 0.9
with wave.open(os.path.join(out, "vo_paced.wav"), "wb") as w:
    w.setnchannels(1); w.setsampwidth(2); w.setframerate(SR)
    w.writeframes((buf * 32767).astype(np.int16).tobytes())
os.remove(raw)
VO_END = timeline[-1]["b"]
with open(os.path.join(out, "timeline.js"), "w") as fh:
    fh.write("// generated by retime_vo.py — narration segment times (seconds) in the paced mix\n")
    fh.write("window.SEG=" + json.dumps(timeline, ensure_ascii=False) + ";\n")
    fh.write(f"window.VO_END={VO_END};\n")
print(f"segments={len(timeline)} voice_end={VO_END:.2f}s file={total:.2f}s")
